#!/usr/bin/env python3
"""Generate the native overlay table (port_overlay_native_table) from ovl_rewrite.py's output.

Usage: gen_ovl_table.py --out <ovl_table.c> [--report <out.txt>] <module.json>...

Each entry is {retail address, size, hash of the
retail bytes, native function}. The stage overlays share 0x80100000 and the weapons 0x800D8800,
so an address alone does not say which module is loaded: port_overlay_native_find() hashes the
function's bytes in RAM and compares (identical bytes mean identical behaviour). The hash is
64-bit FNV-1a over little-endian words (ovl_elf.hash_ranges; the runtime computes the same).

Native functions call other native functions of their module directly. When a function's bytes
also occur at the same address in another module (shared stage code linked at the same place),
a match on them alone would not prove that its direct callees are this module's too; for those
the entry also covers every callee (transitively) whose bytes differ in such a module.

The bytes are read from the matching build's ELFs at build time; only hashes are generated.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ovl_elf import Elf, hash_ranges  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--report")
    ap.add_argument("--retail-ld", help="gen_link.py's linker script: functions it assigns")
    ap.add_argument("modules", nargs="+")
    args = ap.parse_args()

    mods = []
    for path in args.modules:
        with open(path) as f:
            m = json.load(f)
        m["base"], m["image"] = Elf(m["elf"]).image()
        mods.append(m)
    mods.sort(key=lambda m: m["module"])

    def same(a, b, addr, size):
        """Do modules a and b hold the same bytes at [addr, addr+size)?"""
        oa, ob = addr - a["base"], addr - b["base"]
        if oa < 0 or ob < 0 or oa + size > len(a["image"]) or ob + size > len(b["image"]):
            return False
        return a["image"][oa:oa + size] == b["image"][ob:ob + size]

    entries, extra_total, shared = [], 0, 0
    for mi, m in enumerate(mods):
        funcs = {f["name"]: f for f in m["functions"]}
        for f in m["functions"]:
            if f["size"] <= 0 or f["size"] % 4:
                print("gen_ovl_table: %s %s: size %d" % (m["module"], f["name"], f["size"]),
                      file=sys.stderr)
                sys.exit(1)
            ranges = [(f["addr"], f["size"])]
            twins = [o for o in mods if o is not m and same(m, o, f["addr"], f["size"])]
            if twins:
                shared += 1
                seen, todo = set(), list(f["callees"])
                while todo:
                    g = todo.pop()
                    if g in seen or g == f["name"]:
                        continue
                    seen.add(g)
                    todo += funcs[g]["callees"]
                    gf = funcs[g]
                    if any(not same(m, o, gf["addr"], gf["size"]) for o in twins):
                        ranges.append((gf["addr"], gf["size"]))
                extra_total += len(ranges) - 1
            h = hash_ranges(m["base"], m["image"], ranges)
            entries.append((f["addr"], mi, f, ranges, h))
    entries.sort(key=lambda e: (e[0], e[1]))

    # ROCK_NEO.EXE functions the overlay C calls that the main link may not define: the ones
    # retail.ld does not assign (PsyQ routines the port neither runs natively nor emulates yet).
    # Each gets a weak thunk into the interpreter; a real definition (psyq_emulated.c) wins.
    assigned = set()
    if args.retail_ld:
        with open(args.retail_ld) as f:
            for line in f:
                parts = line.split()
                if len(parts) >= 3 and parts[1] == "=":
                    assigned.add(parts[0])
    thunks = {}
    for m in mods:
        for name, addr in m.get("main_functions", {}).items():
            if name not in assigned:
                thunks[name] = addr

    with open(args.out, "w") as out:
        out.write("/* Generated by port/tools/gen_ovl_table.py: native overlay functions. */\n")
        out.write('#include "overlay_native.h"\n#include "mips_cpu.h"\n\n')
        out.write("/* ROCK_NEO.EXE functions not assigned by retail.ld: weak thunks into the\n"
                  "   interpreter (the retail code runs), overridden by any real definition. */\n")
        for name, addr in sorted(thunks.items()):
            out.write("__attribute__((weak)) uint64_t %s(uint32_t a0, uint32_t a1, uint32_t a2, "
                      "uint32_t a3, uint32_t a4, uint32_t a5, uint32_t a6, uint32_t a7)\n"
                      "{\n    const uint32_t a[8] = {a0, a1, a2, a3, a4, a5, a6, a7};\n\n"
                      "    return mips_call64(0x%08XU, a);\n}\n" % (name, addr))
        out.write("\n")
        for _, mi, f, _, _ in entries:
            out.write("void %s(void);\n" % f["native"])
        out.write("\nconst char *const port_overlay_modules[] = {\n")
        for m in mods:
            out.write('    "%s",\n' % m["module"])
        out.write("};\n\n")
        out.write("const PORT_OVL_RANGE port_overlay_ranges[] = {\n")
        index = []
        n = 0
        for _, _, _, ranges, _ in entries:
            index.append(n)
            for a, s in ranges:
                out.write("    {0x%08XU, 0x%XU},\n" % (a, s))
                n += 1
        out.write("};\n\n")
        out.write("const PORT_OVERLAY_NATIVE port_overlay_native_table[] = {\n")
        for (addr, mi, f, ranges, h), first in zip(entries, index):
            out.write('    {0x%08XU, 0x%XU, 0x%016XULL, %d, %d, %d, (void *)%s, "%s"},\n'
                      % (addr, f["size"], h, first, len(ranges), mi, f["native"], f["name"]))
        out.write("};\n")
        out.write("const int port_overlay_native_count = %d;\n" % len(entries))
        out.write("const uint32_t port_overlay_native_lo = 0x%08XU;\n"
                  % (min(e[0] for e in entries)))
        out.write("const uint32_t port_overlay_native_hi = 0x%08XU;\n"
                  % (max(e[0] for e in entries) + 4))

    lines = ["module  native  functions  parked drafts  excluded"]
    tn = tf = 0
    for m in mods:
        r = m["report"]
        lines.append("%-8s %5d  %5d  %3d  %3d" % (m["module"], len(m["functions"]),
                                                 m["module_functions"], len(r["drafts"]),
                                                 len(r["excluded"])))
        tn += len(m["functions"])
        tf += m["module_functions"]
    lines.append("total    %5d  %5d  (%d interpreted)" % (tn, tf, tf - tn))
    lines.append("weak interpreter thunks for ROCK_NEO.EXE functions: %s"
                 % (", ".join(sorted(thunks)) or "-"))
    lines.append("entries sharing their bytes with another module: %d (extra ranges: %d)"
                 % (shared, extra_total))
    for m in mods:
        r = m["report"]
        for key in ("native_only", "data_native", "undefined_unknown"):
            if r.get(key):
                lines.append("%s %s: %s" % (m["module"], key, r[key]))
    if args.report:
        with open(args.report, "w") as f:
            f.write("\n".join(lines) + "\n")
    print("gen_ovl_table: %d native overlay functions of %d in %d modules"
          % (tn, tf, len(mods)))


if __name__ == "__main__":
    main()
