#!/usr/bin/env python3
"""Write the game's function list as a CSV.

Usage:  tools/function_list.py [-o functions.csv]

Columns: Program, File, Confidence, Function, Name, Size, Decompiled, Matched, Reviewed, Score, Depth. One row per
Capcom function: the executables, then the overlays, in address order, then the shared stage code.

- Program: the target (`slus_006.03`, `rock_neo.exe`, `r3_st05`, ...), or `stage_common` for a
  file in src/stage_common/: one source linked into several overlays, listed once (from the
  first overlay that links it). Byte-identical overlay copies (the yamls' `duplicates:`) build
  from the same target and aren't listed.
- File: the yaml subsegment (rock_neo_files.md's split for ROCK_NEO). PsyQ objects and
  hand-written assembly (`asm_*`) are left out.
- Confidence: the first word of the subsegment's yaml comment (confirmed, high, medium, low;
  blank if none).
- Function: splat's default name (`func_<ADDRESS>`; `<file>_func_<OFFSET>` in stage_common);
  Name: the name it was given, blank if none.
- Size: the function's bytes (its ELF symbol's size).
- Decompiled: the function has C, matching or parked in a `#ifdef NON_MATCHING` block.
- Matched: its C builds byte-identical (no NAME.NON_MATCHING symbol in the ELF).
- Reviewed: the owner has read and approved its C (tools/review.py, reviewed.txt): Yes, or
  Changed when the C was edited after the review; blank otherwise.
- Score, Depth: estimated difficulty, and call order (blank once the function has C); see
  func_metrics.py. Sorting by Depth, then Score, gives a decompiling order.

Needs every target built (tools/build.sh all). Regenerated by rebuild.sh.
"""

import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import target_code  # noqa: E402
import review  # noqa: E402
import targets  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PARKED = re.compile(r"#ifdef NON_MATCHING\b(.*?)#endif", re.S)
INCLUDE = re.compile(r'INCLUDE_ASM\("[^"]*",\s*(\w+)\);')


def parked(target):
    """Names of functions with a parked C attempt in the target's C files."""
    names = set()
    for c in targets.sources(target):
        for block in PARKED.findall(c.read_text()):
            names.update(INCLUDE.findall(block))
    return names


YAML_ROW = re.compile(r"^\s*- \[0x[0-9A-Fa-f]+,\s*\.?\w+,\s*([\w/]+)\]\s*(?:#\s*([\w-]+))?")


def confidence(target):
    """{subsegment name: confidence} from the first word of each yaml line's comment."""
    conf = {}
    for line in (ROOT / f"config/{target}/{target}.yaml").read_text().splitlines():
        m = YAML_ROW.match(line)
        if m and m.group(2) in ("confirmed", "high", "medium", "low"):
            conf[m.group(1)] = m.group(2)
    return conf


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--out", default="functions.csv", help="output file (default: functions.csv)")
    args = ap.parse_args()

    import func_metrics  # here, not at the top: it imports this module

    metrics = func_metrics.metrics()
    yn = lambda b: "Yes" if b else "No"
    rows, shared, seen = [], [], set()
    for t in targets.TARGETS:
        funcs, asm = target_code.functions(t)
        subs = target_code.subsegments(t)
        common = set(targets.shared_files(t))
        conf, attempts, reviewed = confidence(t), parked(t), review.status(t)
        for addr in sorted(funcs):
            size, name = funcs[addr]
            sub = next((s for s in subs if s[0] <= addr < s[1]), None)
            if sub is None or sub[2].startswith(("psyq/", "asm_")):
                continue
            file = sub[2]
            if file in common:
                if (file, addr - sub[0]) in seen:
                    continue
                seen.add((file, addr - sub[0]))
                program, default, out = "stage_common", f"{file}_func_{addr - sub[0]:04X}", shared
            else:
                program, default, out = t, f"func_{addr:08X}", rows
            matched = name not in asm
            m = metrics[(t, addr)]
            out.append((program, file, conf.get(file, ""), default, "" if name == default else name, size,
                        yn(matched or name in attempts), yn(matched), reviewed.get(addr, ""),
                        m["score"], m.get("depth", "")))
    rows += sorted(shared, key=lambda r: (r[1], r[3]))

    with open(ROOT / args.out if not Path(args.out).is_absolute() else args.out, "w",
              newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["Program", "File", "Confidence", "Function", "Name", "Size", "Decompiled", "Matched",
                    "Reviewed", "Score", "Depth"])
        w.writerows(rows)

    dec = sum(r[6] == "Yes" for r in rows)
    mat = sum(r[7] == "Yes" for r in rows)
    rev = sum(r[8] == "Yes" for r in rows)
    chg = sum(r[8] == "Changed" for r in rows)
    print(f"wrote {args.out}: {len(rows)} functions, {dec} decompiled, {mat} matched, "
          f"{rev} reviewed{f' ({chg} changed since review)' if chg else ''}, "
          f"{len({(r[0], r[1]) for r in rows})} files")


if __name__ == "__main__":
    main()
