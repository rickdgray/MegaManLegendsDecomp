#!/usr/bin/env python3
"""Write the game's function list as a CSV.

Usage:  tools/function_list.py [-o functions.csv]

Columns: Program, File, Confidence, Function, Name, Decompiled, Matched. One row per Capcom
function, in address order per program.

- Program: `slus_006.03`, `rock_neo.exe`, or an overlay (`ST03`, `ARM05R`, `SUPPORT`). Byte-identical
  overlay copies (ST03B, ...) are left out: they build from the same source.
- File: for the executables, the yaml subsegment (rock_neo_files.md's split); PsyQ objects and
  hand-written assembly (`asm_*`) are left out. For overlays, the split proposed by
  overlay_files.py: a Capcom file name (`eve19`), a common file (`shared_ST03_80107BC0`, the same in
  every overlay that has it), or a region with no evidence yet (`ST03_80100524`).
- Confidence: executables, the first word of the subsegment's yaml comment (confirmed, high,
  medium, low; blank if none). Overlays: `source` (Capcom's source), `shared` (a common file's
  edges), `unknown`.
- Function: splat's default name (`func_<ADDRESS>`); Name: the name it was given, blank if none.
- Decompiled: the function has C, matching or parked in a `#ifdef NON_MATCHING` block.
- Matched: its C builds byte-identical (no NAME.NON_MATCHING symbol in the ELF).

Needs both executables built and tools/extract_overlays.py run once. Regenerated by rebuild.sh.
"""

import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dupe_scan  # noqa: E402
import overlay_files  # noqa: E402
import progress  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
TARGET_OF = {"SLUS": "slus_006.03", "ROCK_NEO": "rock_neo.exe"}
PARKED = re.compile(r"#ifdef NON_MATCHING\b(.*?)#endif", re.S)
INCLUDE = re.compile(r'INCLUDE_ASM\("[^"]*",\s*(\w+)\);')


def parked(target):
    """Names of functions with a parked C attempt in src/<target>/."""
    names = set()
    for c in (ROOT / "src" / target).glob("**/*.c"):
        for block in PARKED.findall(c.read_text()):
            names.update(INCLUDE.findall(block))
    return names


YAML_ROW = re.compile(r"^\s*- \[0x[0-9A-Fa-f]+,\s*\.?\w+,\s*([\w/]+)\]\s*(?:#\s*([\w-]+))?")


def confidence(target):
    """{subsegment name: confidence} from the first word of each yaml line's comment."""
    conf = {}
    for line in (ROOT / f"{target}.yaml").read_text().splitlines():
        m = YAML_ROW.match(line)
        if m and m.group(2) in ("confirmed", "high", "medium", "low"):
            conf[m.group(1)] = m.group(2)
    return conf


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--out", default="functions.csv", help="output file (default: functions.csv)")
    args = ap.parse_args()

    funcs = dupe_scan.collect()
    overlay = overlay_files.assign(funcs)
    subs = {t: progress.subsegments(t) for t in TARGET_OF.values()}
    conf = {t: confidence(t) for t in TARGET_OF.values()}
    attempts = {t: parked(t) for t in TARGET_OF.values()}
    yn = lambda b: "Yes" if b else "No"
    rows = []
    for r in funcs:
        prog, addr, name, matched = r["prog"], r["addr"], r["name"], r["matched"]
        default = f"func_{addr:08X}"
        target = TARGET_OF.get(prog)
        if target is None:
            file, how, _shared = overlay[(prog, addr)]
            rows.append((prog, file, how, default, "", "No", "No"))
            continue
        sub = next((s for s in subs[target] if s[0] <= addr < s[1]), None)
        if sub is None or sub[2].startswith(("psyq/", "asm_")):
            continue
        rows.append((target, sub[2], conf[target].get(sub[2], ""), default,
                     "" if name == default else name, yn(matched or name in attempts[target]),
                     yn(matched)))

    with open(ROOT / args.out if not Path(args.out).is_absolute() else args.out, "w",
              newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["Program", "File", "Confidence", "Function", "Name", "Decompiled", "Matched"])
        w.writerows(rows)

    dec = sum(r[5] == "Yes" for r in rows)
    mat = sum(r[6] == "Yes" for r in rows)
    print(f"wrote {args.out}: {len(rows)} functions, {dec} decompiled, {mat} matched, "
          f"{len({(r[0], r[1]) for r in rows})} files")


if __name__ == "__main__":
    main()
