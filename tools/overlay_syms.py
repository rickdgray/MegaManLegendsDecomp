#!/usr/bin/env python3
"""Write the host executable's symbols for an overlay target's splat run.

Copies the registry lines of ROCK_NEO.EXE whose address lies outside the overlay's own range
[vram, vram + size), so calls and data references from the overlay resolve to ROCK_NEO's names
while the overlay keeps its own. Each line gets absolute:True (see below). The overlay's vram is read from the first segment of its yaml.
Usage: overlay_syms.py <host registry> <overlay chunk> <overlay yaml>  > build/<t>/rock_neo_syms.txt
"""
import os
import re
import sys

import yaml


def main():
    registry, chunk, config = sys.argv[1:4]
    vram = yaml.safe_load(open(config))["segments"][0]["vram"]
    end = vram + os.path.getsize(chunk)
    line_re = re.compile(r"^\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*;")
    print("// Generated by tools/overlay_syms.py from %s; do not edit." % registry)
    for line in open(registry):
        m = line_re.match(line)
        if not m:
            continue
        if vram <= int(m.group(2), 16) < end:
            continue
        # absolute:True: the symbol is outside every segment of the overlay's yaml; splat treats
        # it as defined elsewhere, and build.sh defines it from this file.
        line = line.rstrip("\n")
        if "absolute:True" not in line:
            line += " absolute:True" if "//" in line else " // absolute:True"
        print(line)


if __name__ == "__main__":
    main()
